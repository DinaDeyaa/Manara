# =============================================================================
# MODULE-LEVEL GRAPH CACHE
# =============================================================================
# The graph is parsed once and kept in memory for the lifetime of the process.
# _GRAPH_LOCK serialises concurrent first-load requests.
# Cache is invalidated automatically when the .ttl file mtime changes.

_GRAPH_CACHE: dict = {"graph": None, "mtime": 0.0}
_GRAPH_LOCK  = threading.Lock()


def _get_graph() -> Optional[Graph]:
    """
    Return the cached rdflib.Graph, loading from disk if needed.

    Returns None when the .ttl file does not exist so callers handle
    a missing graph gracefully without crashing the API.
    Cache is invalidated automatically when the file is rebuilt.
    """
    if not OUTPUT_FILE.exists():
        return None

    current_mtime = OUTPUT_FILE.stat().st_mtime

    with _GRAPH_LOCK:
        cached = _GRAPH_CACHE["graph"]
        if cached is not None and _GRAPH_CACHE["mtime"] == current_mtime:
            return cached  # fast path — already loaded, file unchanged

        g = Graph()
        g.parse(str(OUTPUT_FILE), format="turtle")
        _GRAPH_CACHE["graph"] = g
        _GRAPH_CACHE["mtime"] = current_mtime
        print(f"[KG] Graph loaded from disk — {len(g)} triples.")
        return g


def invalidate_graph_cache() -> None:
    """Force the next _get_graph() call to re-read from disk (after rebuild)."""
    with _GRAPH_LOCK:
        _GRAPH_CACHE["graph"] = None
        _GRAPH_CACHE["mtime"] = 0.0


