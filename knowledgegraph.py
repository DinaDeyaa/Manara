def load_graph_for_frontend() -> dict:
    """
    Return a size-capped, frontend-ready payload for InsideManarasBrainPage.

    {
      "nodes":      [...],
      "edges":      [...],
      "is_real":    True | False,
      "node_count": int,
      "edge_count": int,
      "error":      str | None   # present only when is_real=False
    }

    Improvements over the original:
    - Graph read from MODULE-LEVEL CACHE — no disk I/O on repeated requests.
    - Labels come from stored manara:name triples — no URI-slug garbling.
    - Descriptions are meaningful (course code + prereqs for courses).
    - Payload is SERVER-SIDE capped at FRONTEND_MAX_* constants.
    - Returns is_real=False with a clear error when the graph is not built.
      NO fake/demo data is injected.
    - isRelatedTo edges included for cross-course semantic visualization.
    """
    g = _get_graph()
    if g is None:
        return {
            "nodes":   [],
            "edges":   [],
            "is_real": False,
            "error": (
                "Knowledge graph has not been built yet. "
                "Run: python knowledgegraph.py"
            ),
        }

    names = _name_lookup(g)
    desc  = _course_desc_lookup(g, names)

    all_course_uris = [str(subj) for subj, _, _ in g.triples((None, RDF.type, MANARA.Course))]
    course_uri_by_name = {
        names.get(uri, uri.split("/")[-1].replace("_", " ").title()).strip().casefold(): uri
        for uri in all_course_uris
    }

    def _course_uri(course_name: str) -> str:
        key = str(course_name).strip().casefold()
        return course_uri_by_name.get(key, str(make_uri("course", course_name)))

    def _edge_priority(edge: dict) -> tuple[float, int, float]:
        strength = float(edge.get("strength", 0.0) or 0.0)
        link_count = int(edge.get("link_count", 0) or 0)
        avg_distance = float(edge.get("avg_distance", 1.0) or 1.0)
        relationship_boost = {
            "foundational": 1.25,
            "mathematical": 1.12,
            "shared_methods": 1.08,
            "semantic": 1.0,
            "prerequisite": 0.9,
            "hierarchy": 0.2,
        }.get(str(edge.get("relationship", "semantic")), 1.0)
        return (strength * relationship_boost, link_count, 1.0 - avg_distance)

    # Semantic candidate edges are the primary visualization spine. They are
    # already aggregated from subtopic density, so subtopic intelligence drives
    # which course relationships survive the final trim.
    course_semantic_edges = sorted(
        _collect_course_semantic_edges(COURSE_SEMANTIC_EDGE_LIMIT),
        key=_edge_priority,
        reverse=True,
    )
    foundational_edges = _collect_foundational_edges()

    edge_candidates: list[dict] = []
    for edge in foundational_edges + course_semantic_edges:
        src_uri = _course_uri(edge["source_course"])
        tgt_uri = _course_uri(edge["target_course"])
        edge_candidates.append(
            {
                "source_uri": src_uri,
                "target_uri": tgt_uri,
                "source": src_uri.replace(BASE_URI, ""),
                "target": tgt_uri.replace(BASE_URI, ""),
                "label": edge.get("label", "isSemanticallyRelatedTo"),
                "relationship": edge.get("relationship", "semantic"),
                "strength": edge.get("strength", 0.5),
                "link_count": edge.get("link_count", 0),
                "avg_distance": edge.get("avg_distance", 1.0),
                "shared_concepts": edge.get("shared_concepts", []),
                "explanation": edge.get("explanation", "Connected by Manara's semantic knowledge graph."),
            }
        )

    edge_candidates.sort(key=_edge_priority, reverse=True)

    # Selection is relationship-first:
    #   1. seed from strongest semantic/foundational edges
    #   2. recursively include strong neighbors
    #   3. include endpoints before final edge trimming
    selected_nodes: set[str] = set()
    node_scores: Counter[str] = Counter()
    adjacency: dict[str, list[dict]] = defaultdict(list)

    for edge in edge_candidates:
        src = edge["source_uri"]
        tgt = edge["target_uri"]
        adjacency[src].append(edge)
        adjacency[tgt].append(edge)
        score = _edge_priority(edge)[0] + min(2.5, int(edge.get("link_count", 0) or 0) / 80)
        node_scores[src] += score
        node_scores[tgt] += score

    for edge in edge_candidates:
        if len(selected_nodes) >= FRONTEND_MAX_COURSE_NODES:
            break
        selected_nodes.add(edge["source_uri"])
        selected_nodes.add(edge["target_uri"])

    for _ in range(2):
        expanded = False
        for node_uri in list(selected_nodes):
            strong_neighbors = sorted(
                adjacency.get(node_uri, []),
                key=_edge_priority,
                reverse=True,
            )
            for edge in strong_neighbors[:8]:
                other = edge["target_uri"] if edge["source_uri"] == node_uri else edge["source_uri"]
                if other in selected_nodes:
                    continue
                if (
                    float(edge.get("strength", 0) or 0) >= 0.55
                    or int(edge.get("link_count", 0) or 0) >= 5
                    or edge.get("relationship") == "foundational"
                ):
                    selected_nodes.add(other)
                    expanded = True
                if len(selected_nodes) >= FRONTEND_MAX_COURSE_NODES:
                    break
            if len(selected_nodes) >= FRONTEND_MAX_COURSE_NODES:
                break
        if not expanded:
            break

    if len(selected_nodes) < FRONTEND_MAX_COURSE_NODES:
        for uri, _ in node_scores.most_common(FRONTEND_MAX_COURSE_NODES):
            selected_nodes.add(uri)
            if len(selected_nodes) >= FRONTEND_MAX_COURSE_NODES:
                break

    # Add a small, scored topic context after the course semantic skeleton is
    # fixed. This preserves curriculum structure without letting topic order
    # destroy course-to-course connectivity.
    selected_topics: set[str] = set()
    topic_scores: Counter[str] = Counter()
    for course_uri in selected_nodes:
        for _, _, topic_uri in g.triples((URIRef(course_uri), MANARA.hasTopic, None)):
            topic_scores[str(topic_uri)] += max(node_scores.get(course_uri, 1), 1)

    for topic_uri, _ in topic_scores.most_common(FRONTEND_MAX_TOPIC_NODES):
        selected_topics.add(topic_uri)

    all_selected = set(selected_nodes) | selected_topics

    nodes: list[dict] = []
    added_nodes: set[str] = set()

    def _make_node(uri_str: str) -> Optional[dict]:
        node_id = uri_str.replace(BASE_URI, "")
        node_type = _detect_node_type(node_id)
        if node_type == "hidden":
            return None
        label = names.get(uri_str)
        if not label:
            raw = node_id.split("/")[-1]
            raw = re.sub(r"_\d+$", "", raw)
            label = raw.replace("_", " ").title()
        label = str(label).strip()
        node_desc = desc.get(uri_str, label) if node_type == "course" else label
        return {
            "id": node_id,
            "label": label,
            "display_label": label,
            "type": node_type,
            "desc": node_desc,
            "score": round(float(node_scores.get(uri_str, topic_scores.get(uri_str, 0))), 3),
        }

    def _ensure_node(uri_str: str) -> None:
        if uri_str in added_nodes:
            return
        n = _make_node(uri_str)
        if n:
            nodes.append(n)
            added_nodes.add(uri_str)

    for uri_str in sorted(all_selected, key=lambda u: node_scores.get(u, topic_scores.get(u, 0)), reverse=True):
        _ensure_node(uri_str)

    edge_keys: set[tuple[str, str, str]] = set()
    candidate_edges: list[dict] = []

    def _add_candidate(edge: dict) -> None:
        key = (str(edge.get("source")), str(edge.get("target")), str(edge.get("label", "")))
        rev_key = (key[1], key[0], key[2])
        if key in edge_keys or rev_key in edge_keys:
            return
        edge_keys.add(key)
        candidate_edges.append(edge)

    # Always include selected semantic/foundational endpoints before trimming.
    for edge in edge_candidates:
        if edge["source_uri"] not in all_selected and edge["target_uri"] not in all_selected:
            continue
        if edge["source_uri"] not in all_selected and len(selected_nodes) < FRONTEND_MAX_COURSE_NODES:
            selected_nodes.add(edge["source_uri"])
            all_selected.add(edge["source_uri"])
            _ensure_node(edge["source_uri"])
        if edge["target_uri"] not in all_selected and len(selected_nodes) < FRONTEND_MAX_COURSE_NODES:
            selected_nodes.add(edge["target_uri"])
            all_selected.add(edge["target_uri"])
            _ensure_node(edge["target_uri"])
        if edge["source_uri"] in all_selected and edge["target_uri"] in all_selected:
            _add_candidate({k: v for k, v in edge.items() if not k.endswith("_uri")})

    relationship_map = {
        "hasPrerequisite": "prerequisite",
        "hasConcurrent": "prerequisite",
        "hasTopic": "hierarchy",
        "hasSubtopic": "hierarchy",
        "isRelatedTo": "semantic",
        "isSemanticallySimilarTo": "semantic",
        "isSemanticallyRelatedTo": "semantic",
        "sharesMathematicsWith": "mathematical",
        "sharesMethodsWith": "shared_methods",
        "isFoundationalFor": "foundational",
        "extendsConceptsFrom": "foundational",
    }
    allowed = set(relationship_map)

    rdf_edges_seen = 0
    endpoint_expansions = 0
    for subj, pred, obj in g:
        if not isinstance(obj, URIRef):
            continue
        pred_name = str(pred).split("/")[-1]
        if pred_name not in allowed:
            continue

        subj_str = str(subj)
        obj_str = str(obj)
        relationship = relationship_map[pred_name]

        if subj_str not in all_selected or obj_str not in all_selected:
            important = relationship in {"semantic", "mathematical", "shared_methods", "foundational", "prerequisite"}
            if not important:
                continue

            # Fix the old aggressive endpoint filter: important relationships
            # can pull in their missing endpoint while we still have capacity.
            if subj_str in all_selected and obj_str not in all_selected and _detect_node_type(obj_str.replace(BASE_URI, "")) == "course":
                if len(selected_nodes) < FRONTEND_MAX_COURSE_NODES:
                    selected_nodes.add(obj_str)
                    all_selected.add(obj_str)
                    _ensure_node(obj_str)
                    endpoint_expansions += 1
                else:
                    continue
            elif obj_str in all_selected and subj_str not in all_selected and _detect_node_type(subj_str.replace(BASE_URI, "")) == "course":
                if len(selected_nodes) < FRONTEND_MAX_COURSE_NODES:
                    selected_nodes.add(subj_str)
                    all_selected.add(subj_str)
                    _ensure_node(subj_str)
                    endpoint_expansions += 1
                else:
                    continue
            else:
                continue

        subj_id = subj_str.replace(BASE_URI, "")
        obj_id = obj_str.replace(BASE_URI, "")
        if _detect_node_type(subj_id) == "hidden" or _detect_node_type(obj_id) == "hidden":
            continue

        _ensure_node(subj_str)
        _ensure_node(obj_str)
        rdf_edges_seen += 1
        base_strength = {
            "foundational": 0.95,
            "prerequisite": 0.8,
            "semantic": 0.55,
            "mathematical": 0.65,
            "shared_methods": 0.65,
            "hierarchy": 0.25,
        }.get(relationship, 0.4)
        _add_candidate(
            {
                "source": subj_id,
                "target": obj_id,
                "label": pred_name,
                "relationship": relationship,
                "strength": base_strength,
                "link_count": 0,
                "shared_concepts": [],
                "explanation": f"Connected by graph relationship: {pred_name}.",
            }
        )

    candidate_edges.sort(key=_edge_priority, reverse=True)
    edges = candidate_edges[:FRONTEND_MAX_EDGES]

    relationship_counts = Counter(str(e.get("relationship", "unknown")) for e in edges)
    semantic_edges_generated = sum(
        1 for e in edges
        if e.get("relationship") in {"semantic", "mathematical", "shared_methods"}
    )
    filtered_edges = max(0, len(candidate_edges) - len(edges))

    print(
        "[KG DEBUG] Frontend graph payload: "
        f"nodes={len(nodes)} edges={len(edges)} candidates={len(candidate_edges)} "
        f"semantic_edges={semantic_edges_generated} endpoint_expansions={endpoint_expansions} "
        f"rdf_edges_seen={rdf_edges_seen} relationship_counts={dict(relationship_counts)}"
    )
    return {
        "nodes": nodes,
        "edges": edges,
        "is_real": True,
        "node_count": len(nodes),
        "edge_count": len(edges),
        "debug": {
            "candidate_edges_count": len(candidate_edges),
            "semantic_edges_generated": semantic_edges_generated,
            "relationship_counts": dict(relationship_counts),
            "rendered_edges_count": len(edges),
            "filtered_edges_count": filtered_edges,
            "endpoint_expansions": endpoint_expansions,
            "rdf_edges_seen": rdf_edges_seen,
            "selection_strategy": "semantic_expand_then_trim",
        },
    }


