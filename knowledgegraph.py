def safe_id(text: str) -> str:
    """Slug a string to a URI-safe identifier."""
    return re.sub(r"[^a-zA-Z0-9_]+", "_", text.strip().lower()).strip("_")


def make_uri(entity_type: str, identifier: str) -> URIRef:
    return EX[f"{entity_type}/{safe_id(identifier)}"]


def get_course_folders(courses_dir: Path) -> list[Path]:
    if not courses_dir.exists():
        return []
    return sorted([p for p in courses_dir.iterdir() if p.is_dir()])


def _load_json(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _name_lookup(g: Graph) -> dict[str, str]:
    """Build {uri_str -> human_name} from every manara:name triple."""
    return {
        str(subj): str(obj).strip()
        for subj, pred, obj in g
        if str(pred) == str(MANARA.name) and isinstance(obj, Literal)
    }


def _detect_node_type(node_id: str) -> str:
    """Return 'course', 'topic', or 'hidden' for a URI path segment."""
    low = node_id.lower()
    if low.startswith("course/"):
        return "course"
    if low.startswith("topic/") or low.startswith("subtopic/"):
        return "topic"
    return "hidden"


def _find_course_uri(g: Graph, course_name: str) -> Optional[URIRef]:
    """Look up a course URIRef by stored manara:name, with slug fallback."""
    for subj, _, _ in g.triples((None, MANARA.name, Literal(course_name))):
        if (subj, RDF.type, MANARA.Course) in g:
            return subj
    # Slug fallback for minor capitalisation/spacing differences
    candidate = EX[f"course/{safe_id(course_name)}"]
    if (candidate, RDF.type, MANARA.Course) in g:
        return candidate
    return None


def _course_desc_lookup(g: Graph, names: dict[str, str]) -> dict[str, str]:
    """
    Build {course_uri_str -> description} from courseCode + prerequisite names.
    Example: "Code: 14260 | Requires: Introduction to Data Science"
    """
    desc: dict[str, str] = {}
    for subj, _, obj in g.triples((None, MANARA.courseCode, None)):
        code  = str(obj)
        parts = [f"Code: {code}"]
        prereqs = [
            names.get(str(o), str(o).split("/")[-1].replace("_", " "))
            for _, _, o in g.triples((subj, MANARA.hasPrerequisite, None))
        ]
        if prereqs:
            parts.append("Requires: " + ", ".join(prereqs))
        desc[str(subj)] = " | ".join(parts)
    return desc


