def get_courses_by_prerequisite_distance(target_course: str) -> list[tuple[str, int]]:
    """
    BFS from target_course along hasPrerequisite edges.

    Returns [(course_name, distance)] sorted by distance ascending.
      distance 1 = direct prerequisite
      distance 2 = prerequisite of prerequisite

    Returns [] if graph not built or course not found.

    Used by api_server.py to:
      - Prioritise diagnostic subtopic sampling from closest prereq courses
      - Sort learning path steps foundationally
    """
    g = _get_graph()
    if g is None:
        return []

    names      = _name_lookup(g)
    target_uri = _find_course_uri(g, target_course)
    if target_uri is None:
        return []

    visited: dict[str, int] = {}
    queue: list[tuple[URIRef, int]] = [(target_uri, 0)]

    while queue:
        current, dist = queue.pop(0)
        for _, _, prereq_uri in g.triples((current, MANARA.hasPrerequisite, None)):
            key = str(prereq_uri)
            if key in visited:
                continue
            visited[key] = dist + 1
            queue.append((prereq_uri, dist + 1))

    result = [
        (names.get(uri, uri.split("/")[-1].replace("_", " ")), dist)
        for uri, dist in visited.items()
    ]
    result.sort(key=lambda x: x[1])
    return result


def get_prerequisite_chain(target_course: str) -> list[str]:
    """Return prerequisite course names in BFS order (closest first)."""
    return [name for name, _ in get_courses_by_prerequisite_distance(target_course)]


def get_subtopics_for_course_via_graph(course_name: str) -> list[dict]:
    """
    Return all subtopics for course_name by traversing the graph:
      Course -> hasTopic -> Topic -> hasSubtopic -> Subtopic

    Returns [{"course_name", "topic_name", "subtopic_name"}, ...]

    Used by api_server.py to drive diagnostic sampling from graph data
    instead of re-reading raw JSON files on every request.
    """
    g = _get_graph()
    if g is None:
        return []

    names      = _name_lookup(g)
    course_uri = _find_course_uri(g, course_name)
    if course_uri is None:
        return []

    results: list[dict] = []
    for _, _, topic_uri in g.triples((course_uri, MANARA.hasTopic, None)):
        topic_name = names.get(str(topic_uri), "")
        if not topic_name:
            continue
        for _, _, sub_uri in g.triples((topic_uri, MANARA.hasSubtopic, None)):
            sub_name = names.get(str(sub_uri), "")
            if not sub_name:
                continue
            results.append({
                "course_name":   course_name,
                "topic_name":    topic_name,
                "subtopic_name": sub_name,
            })

    return results


def get_related_topics_for_course(course_name: str, limit: int = 20) -> list[dict]:
    """
    Return cross-course topics semantically related to topics in course_name.

    Returns [{"source_topic", "target_course", "target_topic"}, ...]

    Used by diagnostic sampling to pull related material from prerequisite
    courses even when topic names differ.
    """
    g = _get_graph()
    if g is None:
        return []

    names      = _name_lookup(g)
    course_uri = _find_course_uri(g, course_name)
    if course_uri is None:
        return []

    results: list[dict] = []
    seen: set[tuple[str, str]] = set()

    for _, _, topic_uri in g.triples((course_uri, MANARA.hasTopic, None)):
        src_name = names.get(str(topic_uri), "")
        for _, _, rel_uri in g.triples((topic_uri, MANARA.isRelatedTo, None)):
            rel_name = names.get(str(rel_uri), "")
            if not rel_name:
                continue
            for owning_uri, _, _ in g.triples((None, MANARA.hasTopic, rel_uri)):
                oc_name = names.get(str(owning_uri), "")
                if oc_name == course_name:
                    continue
                key = (src_name, rel_name)
                if key in seen:
                    continue
                seen.add(key)
                results.append({
                    "source_topic":  src_name,
                    "target_course": oc_name,
                    "target_topic":  rel_name,
                })
                if len(results) >= limit:
                    return results

    return results


