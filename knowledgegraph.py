def get_semantically_related_subtopics(
    course_name:   str,
    subtopic_name: str,
    limit:         int = 10,
) -> list[dict]:
    """
    Return subtopics from OTHER courses that are semantically similar to the
    given subtopic, via manara:isSemanticallySimilarTo edges.

    Returns [{"target_course", "target_topic", "target_subtopic"}, ...]
    sorted arbitrarily (graph traversal order).

    Returns [] if:
      - graph not built
      - subtopic not found in graph
      - no isSemanticallySimilarTo edges exist (graph not yet rebuilt after
        running related_subtopic_analysis.py with the new subtopic CSV)

    Used by api_server.py to enrich learning path steps with semantically
    related concepts from across the entire curriculum.
    """
    g = _get_graph()
    if g is None:
        return []

    names = _name_lookup(g)

    # Locate the subtopic URI — try (course, subtopic) key first
    sub_uri = EX[f"subtopic/{safe_id(course_name + '_' + subtopic_name)}"]
    if (sub_uri, RDF.type, MANARA.Subtopic) not in g:
        # Fallback: scan all Subtopic nodes matching the name in this course
        sub_uri = None
        course_uri = _find_course_uri(g, course_name)
        if course_uri is None:
            return []
        for _, _, topic_uri in g.triples((course_uri, MANARA.hasTopic, None)):
            for _, _, s_uri in g.triples((topic_uri, MANARA.hasSubtopic, None)):
                if names.get(str(s_uri), "") == subtopic_name:
                    sub_uri = s_uri
                    break
            if sub_uri is not None:
                break
        if sub_uri is None:
            return []

    results: list[dict] = []
    seen:    set[str]   = set()

    for _, _, rel_uri in g.triples((sub_uri, MANARA.isSemanticallySimilarTo, None)):
        rel_name = names.get(str(rel_uri), "")
        if not rel_name or rel_name in seen:
            continue
        seen.add(rel_name)

        # Walk up: rel_uri → Topic → Course
        target_topic  = ""
        target_course = ""
        for topic_uri, _, _ in g.triples((None, MANARA.hasSubtopic, rel_uri)):
            target_topic = names.get(str(topic_uri), "")
            for course_uri, _, _ in g.triples((None, MANARA.hasTopic, topic_uri)):
                target_course = names.get(str(course_uri), "")
                break
            break

        if target_course == course_name:
            continue  # skip same-course edges (should not exist, but guard anyway)

        results.append({
            "target_course":   target_course,
            "target_topic":    target_topic,
            "target_subtopic": rel_name,
        })
        if len(results) >= limit:
            break

    return results


