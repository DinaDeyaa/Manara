def _add_schema(g: Graph) -> None:
    g.bind("ex",     EX)
    g.bind("manara", MANARA)
    g.bind("rdf",    RDF)
    g.bind("rdfs",   RDFS)
    g.bind("owl",    OWL)

    for cls in ("Course", "Material", "Topic", "Subtopic", "Keyword"):
        g.add((MANARA[cls], RDF.type,   OWL.Class))
        g.add((MANARA[cls], RDFS.label, Literal(cls)))

    object_props = {
        "hasPrerequisite":        ("Course",   "Course"),
        "hasConcurrent":          ("Course",   "Course"),
        "hasMaterial":            ("Course",   "Material"),
        "hasTopic":               ("Course",   "Topic"),
        "coversTopic":            ("Material", "Topic"),
        "hasSubtopic":            ("Topic",    "Subtopic"),
        "hasKeyword":             ("Topic",    "Keyword"),
        "isRelatedTo":            ("Topic",    "Topic"),    # legacy cross-course topic edge
        "isSemanticallySimilarTo": ("Subtopic", "Subtopic"), # new cross-course subtopic edge
        "isSemanticallyRelatedTo": ("Course",   "Course"),   # aggregated semantic course edge
        "sharesMathematicsWith":   ("Course",   "Course"),
        "sharesMethodsWith":       ("Course",   "Course"),
        "isFoundationalFor":       ("Course",   "Course"),
        "extendsConceptsFrom":     ("Course",   "Course"),
    }
    for prop, (domain, rng) in object_props.items():
        g.add((MANARA[prop], RDF.type,    OWL.ObjectProperty))
        g.add((MANARA[prop], RDFS.domain, MANARA[domain]))
        g.add((MANARA[prop], RDFS.range,  MANARA[rng]))
        g.add((MANARA[prop], RDFS.label,  Literal(prop)))

    for prop in ("name", "courseCode", "chapter", "fileName",
                 "relativePath", "fileType", "similarityScore",
                 "relationshipStrength", "relationshipExplanation",
                 "sharedConcepts", "semanticLinkCount"):
        g.add((MANARA[prop], RDF.type,   OWL.DatatypeProperty))
        g.add((MANARA[prop], RDFS.label, Literal(prop)))


