def graph_status() -> dict:
    """Return a health/status dict for /api/graph/status."""
    if not OUTPUT_FILE.exists():
        return {
            "built":       False,
            "path":        str(OUTPUT_FILE),
            "triple_count": 0,
            "message":     "Graph not built. Run `python knowledgegraph.py`.",
        }

    g = _get_graph()
    if g is None:
        return {
            "built":       False,
            "path":        str(OUTPUT_FILE),
            "triple_count": 0,
            "message":     "Graph file exists but could not be parsed.",
        }

    import datetime
    mtime    = OUTPUT_FILE.stat().st_mtime
    built_at = datetime.datetime.fromtimestamp(mtime).strftime("%Y-%m-%d %H:%M:%S")

    semantic_subtopic_edges = sum(
        1 for _ in g.triples((None, MANARA.isSemanticallySimilarTo, None))
    ) // 2
    legacy_topic_edges = sum(
        1 for _ in g.triples((None, MANARA.isRelatedTo, None))
    ) // 2
    course_semantic_edges = (
        sum(1 for _ in g.triples((None, MANARA.isSemanticallyRelatedTo, None)))
        + sum(1 for _ in g.triples((None, MANARA.sharesMathematicsWith, None)))
        + sum(1 for _ in g.triples((None, MANARA.sharesMethodsWith, None)))
    ) // 2
    foundational_edges = (
        sum(1 for _ in g.triples((None, MANARA.isFoundationalFor, None)))
        + sum(1 for _ in g.triples((None, MANARA.extendsConceptsFrom, None)))
    )

    return {
        "built":                        True,
        "path":                         str(OUTPUT_FILE),
        "triple_count":                 len(g),
        "courses":                      sum(1 for _ in g.triples((None, RDF.type, MANARA.Course))),
        "topics":                       sum(1 for _ in g.triples((None, RDF.type, MANARA.Topic))),
        "subtopics":                    sum(1 for _ in g.triples((None, RDF.type, MANARA.Subtopic))),
        "semantic_subtopic_edges":      semantic_subtopic_edges,
        "legacy_topic_edges":           legacy_topic_edges,
        "course_semantic_edges":        course_semantic_edges,
        "foundational_edges":           foundational_edges,
        "cross_course_edges":           semantic_subtopic_edges + legacy_topic_edges + course_semantic_edges + foundational_edges,
        "built_at":                     built_at,
        "message":                      "Graph is loaded and ready.",
    }


