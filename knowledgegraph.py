"""
knowledgegraph.py — Manara Semantic Knowledge Graph
====================================================

This module is the single source of truth for all graph-based intelligence
in Manara.  It owns:

  • Building the RDF/OWL graph from course data files
  • Serialising to Turtle (.ttl)
  • Loading the graph with a module-level cache (parsed once per process)
  • Prerequisite BFS traversal (secondary metadata — NOT primary intelligence)
  • Cross-course semantic edge injection (from related_subtopics.csv)
  • Frontend-ready payload generation (for InsideManarasBrainPage)
  • Query helpers used by api_server.py

Architecture rules
──────────────────
1.  The graph is parsed from disk ONCE per process and cached in _GRAPH_CACHE.
    Every public function that needs the graph calls _get_graph(), which
    returns the cached instance.  Disk reads happen only on first call or
    after rebuild.

2.  build_knowledge_graph() is the only function that writes to disk.
    It must be called manually (python knowledgegraph.py) or via the
    /api/graph/rebuild endpoint after course data changes.

3.  No fake/demo/fallback data is generated by this module.  If the .ttl
    file does not exist, callers receive an empty result and a clear error
    message telling them to run the build.

4.  All public functions are safe to call from FastAPI route handlers and
    from background threads.

5.  Topic URIs include a per-course prefix AND the topic index to prevent
    collisions between same-named topics in different courses:
        topic/<safe_course>_<safe_topic>_<index>

6.  Subtopic URIs include the course prefix to prevent global collisions:
        subtopic/<safe_course>_<safe_subtopic>

7.  Cross-course semantic edges are injected from related_subtopics.csv at
    build time.  Two edge types are supported, auto-detected from CSV columns:

      NEW (preferred): source_subtopic / target_subtopic columns present
        → manara:isSemanticallySimilarTo edges between Subtopic nodes

      LEGACY: only source_topic / target_topic columns present
        → manara:isRelatedTo edges between Topic nodes (backward-compat)

    Both edge types are symmetric (A→B and B→A both stored).
    Only pairs with ChromaDB distance <= SIMILARITY_THRESHOLD are included.

8.  Manara's primary intelligence is semantic similarity across ALL courses
    globally, driven by SUBTOPIC-granularity isSemanticallySimilarTo edges.
    Prerequisites are metadata only — they are NOT used as the primary
    driver of diagnostic sampling or learning path ordering.
"""

