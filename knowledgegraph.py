def build_knowledge_graph(courses_dir: Path = COURSES_DIR) -> Graph:
    """
    Build the full RDF graph from all course data files and return it.

    Data sources (in order):
      1. courses/<name>/metadata/prerequisites.json   -> Course nodes + prereq edges
      2. courses/<name>/metadata/materials_index.json -> Material nodes
      3. courses/<name>/outputs/chapter_concepts.json -> Topic + Subtopic nodes
      4. related_subtopics.csv (project root)          -> isRelatedTo edges

    rdflib.Graph uses a set internally so adding the same triple twice is a
    no-op — duplicate nodes and edges cannot appear.

    URI collision prevention:
      - Topic URIs   = topic/<course_slug>_<topic_slug>_<index>
      - Subtopic URIs = subtopic/<course_slug>_<subtopic_slug>
    """
    g = Graph()
    _add_schema(g)

    # (course_name, topic_name)    -> URIRef  — for isRelatedTo (legacy) edge injection
    topic_uri_map: dict[tuple[str, str], URIRef] = {}
    # (course_name, subtopic_name) -> URIRef  — for isSemanticallySimilarTo edge injection
    subtopic_uri_map: dict[tuple[str, str], URIRef] = {}

    for course_dir in get_course_folders(courses_dir):
        course_name  = course_dir.name
        metadata_dir = course_dir / "metadata"
        outputs_dir  = course_dir / "outputs"

        course_uri = make_uri("course", course_name)
        g.add((course_uri, RDF.type,    MANARA.Course))
        g.add((course_uri, MANARA.name, Literal(course_name)))
        g.add((course_uri, RDFS.label,  Literal(course_name)))

        # -- Prerequisites -------------------------------------------------
        prereq_file = metadata_dir / "prerequisites.json"
        if prereq_file.exists():
            try:
                prereq_data = _load_json(prereq_file)
            except Exception as e:
                print(f"[KG] Bad prerequisites.json for {course_name}: {e}")
                prereq_data = {}

            code = prereq_data.get("course_code", "")
            if code:
                g.add((course_uri, MANARA.courseCode, Literal(str(code))))

            for prereq in prereq_data.get("prerequisites", []):
                prereq = str(prereq).strip()
                if not prereq:
                    continue
                prereq_uri = make_uri("course", prereq)
                g.add((prereq_uri, RDF.type,    MANARA.Course))
                g.add((prereq_uri, MANARA.name, Literal(prereq)))
                g.add((prereq_uri, RDFS.label,  Literal(prereq)))
                g.add((course_uri, MANARA.hasPrerequisite, prereq_uri))

            for concurrent in prereq_data.get("concurrent", []):
                concurrent = str(concurrent).strip()
                if not concurrent:
                    continue
                conc_uri = make_uri("course", concurrent)
                g.add((conc_uri,   RDF.type,    MANARA.Course))
                g.add((conc_uri,   MANARA.name, Literal(concurrent)))
                g.add((conc_uri,   RDFS.label,  Literal(concurrent)))
                g.add((course_uri, MANARA.hasConcurrent, conc_uri))

        # -- Materials -----------------------------------------------------
        materials_map: dict[str, URIRef] = {}
        mat_file = metadata_dir / "materials_index.json"
        if mat_file.exists():
            try:
                mat_data = _load_json(mat_file)
            except Exception as e:
                print(f"[KG] Bad materials_index.json for {course_name}: {e}")
                mat_data = {}

            for mat in mat_data.get("materials", []):
                rel_path  = str(mat.get("relative_path", "")).strip()
                mat_id    = mat.get("material_id") or safe_id(rel_path) or safe_id(course_name + "_mat")
                mat_uri   = make_uri("material", mat_id)
                file_name = str(mat.get("file_name", mat_id))

                materials_map[rel_path] = mat_uri
                g.add((mat_uri,    RDF.type,            MANARA.Material))
                g.add((mat_uri,    RDFS.label,          Literal(file_name)))
                g.add((mat_uri,    MANARA.fileName,     Literal(file_name)))
                g.add((mat_uri,    MANARA.relativePath, Literal(rel_path)))
                g.add((mat_uri,    MANARA.fileType,     Literal(str(mat.get("file_type", "")))))
                g.add((mat_uri,    MANARA.chapter,      Literal(str(mat.get("chapter", "")))))
                g.add((course_uri, MANARA.hasMaterial,  mat_uri))

        # -- Topics & Subtopics -------------------------------------------
        concepts_file = outputs_dir / "chapter_concepts.json"
        if concepts_file.exists():
            try:
                concepts_data = _load_json(concepts_file)
            except Exception as e:
                print(f"[KG] Bad chapter_concepts.json for {course_name}: {e}")
                concepts_data = {}

            for relative_path, content in concepts_data.items():
                chapter     = str(content.get("chapter", "")).strip()
                mat_uri_ref = materials_map.get(relative_path)

                for topic_index, topic in enumerate(content.get("topics", [])):
                    topic_name = str(topic.get("topic_name", "")).strip()
                    if not topic_name:
                        continue

                    # Include course + index to prevent cross-course URI collisions
                    topic_uri = make_uri(
                        "topic",
                        f"{course_name}_{topic_name}_{topic_index}",
                    )

                    g.add((topic_uri,  RDF.type,       MANARA.Topic))
                    g.add((topic_uri,  MANARA.name,    Literal(topic_name)))
                    g.add((topic_uri,  MANARA.chapter, Literal(chapter)))
                    g.add((topic_uri,  RDFS.label,     Literal(topic_name)))
                    g.add((course_uri, MANARA.hasTopic, topic_uri))

                    if mat_uri_ref is not None:
                        g.add((mat_uri_ref, MANARA.coversTopic, topic_uri))

                    # Register for cross-course edge injection.
                    # If the same topic_name appears in multiple chapters of the
                    # same course, last URI wins — acceptable for lookup.
                    topic_uri_map[(course_name, topic_name)] = topic_uri

                    for subtopic in topic.get("subtopics", []):
                        subtopic = str(subtopic).strip()
                        if not subtopic:
                            continue
                        sub_uri = make_uri("subtopic", f"{course_name}_{subtopic}")
                        g.add((sub_uri,   RDF.type,          MANARA.Subtopic))
                        g.add((sub_uri,   MANARA.name,       Literal(subtopic)))
                        g.add((sub_uri,   RDFS.label,        Literal(subtopic)))
                        g.add((topic_uri, MANARA.hasSubtopic, sub_uri))

                        # Register for cross-course subtopic edge injection.
                        # If the same subtopic_name appears in multiple topics of
                        # the same course, last URI wins — acceptable for lookup.
                        subtopic_uri_map[(course_name, subtopic)] = sub_uri

                    for keyword in topic.get("keywords", []):
                        keyword = str(keyword).strip()
                        if not keyword:
                            continue
                        kw_uri = make_uri("keyword", keyword)
                        g.add((kw_uri,    RDF.type,         MANARA.Keyword))
                        g.add((kw_uri,    MANARA.name,      Literal(keyword)))
                        g.add((kw_uri,    RDFS.label,       Literal(keyword)))
                        g.add((topic_uri, MANARA.hasKeyword, kw_uri))

    # -- Cross-course semantic edges ---------------------------------------
    _inject_related_topic_edges(g, topic_uri_map, subtopic_uri_map)
    _inject_course_semantic_edges(g)
    _inject_foundational_course_edges(g)

    return g


def _inject_related_topic_edges(
    g:               Graph,
    topic_uri_map:   dict[tuple[str, str], URIRef],
    subtopic_uri_map: dict[tuple[str, str], URIRef],
) -> None:
    """
    Read related_subtopics.csv and add bidirectional semantic edges between
    nodes from DIFFERENT courses whose distance <= SIMILARITY_THRESHOLD.

    Auto-detects CSV format from column headers:

      NEW format (subtopic-level — preferred):
        Columns: source_course, source_topic, source_subtopic,
                 target_course, target_topic, target_subtopic, distance
        → injects manara:isSemanticallySimilarTo between Subtopic URIs

      LEGACY format (topic-level — backward-compatible):
        Columns: source_course, source_topic, target_course, target_topic, distance
        → injects manara:isRelatedTo between Topic URIs

    Skips silently if the CSV is missing.
    Deduplicates within each edge type using a sorted-pair set.
    """
    if not RELATED_CSV.exists():
        print("[KG] related_subtopics.csv not found — no cross-course edges added.")
        print("     Run related_subtopic_analysis.py to generate it.")
        return

    subtopic_added: set[tuple[str, str]] = set()
    topic_added:    set[tuple[str, str]] = set()
    subtopic_edge_count = 0
    topic_edge_count    = 0
    skip_count          = 0

    try:
        with open(RELATED_CSV, "r", encoding="utf-8-sig", newline="") as f:
            reader    = csv.DictReader(f)
            fieldnames = [fn.strip() for fn in (reader.fieldnames or [])]

            # Detect which mode to run based on column presence
            has_subtopic_cols = (
                "source_subtopic" in fieldnames
                and "target_subtopic" in fieldnames
            )

            if has_subtopic_cols:
                print("[KG] Detected NEW subtopic-level CSV — injecting "
                      "isSemanticallySimilarTo edges.")
            else:
                print("[KG] Detected LEGACY topic-level CSV — injecting "
                      "isRelatedTo edges (run related_subtopic_analysis.py "
                      "to upgrade to subtopic-level).")

            for row in reader:
                src_course = str(row.get("source_course", "")).strip()
                tgt_course = str(row.get("target_course", "")).strip()
                dist_str   = str(row.get("distance", "1")).strip()

                if src_course == tgt_course:
                    continue

                try:
                    distance = float(dist_str)
                except ValueError:
                    continue

                if distance > SIMILARITY_THRESHOLD:
                    continue

                if has_subtopic_cols:
                    # ---- NEW: Subtopic ↔ Subtopic edges ------------------
                    src_sub = str(row.get("source_subtopic", "")).strip()
                    tgt_sub = str(row.get("target_subtopic", "")).strip()

                    if not src_sub or not tgt_sub:
                        skip_count += 1
                        continue

                    src_uri = subtopic_uri_map.get((src_course, src_sub))
                    tgt_uri = subtopic_uri_map.get((tgt_course, tgt_sub))

                    if src_uri is None or tgt_uri is None:
                        skip_count += 1
                        continue

                    pair = tuple(sorted([str(src_uri), str(tgt_uri)]))
                    if pair in subtopic_added:
                        continue
                    subtopic_added.add(pair)

                    g.add((src_uri, MANARA.isSemanticallySimilarTo, tgt_uri))
                    g.add((tgt_uri, MANARA.isSemanticallySimilarTo, src_uri))
                    subtopic_edge_count += 1

                else:
                    # ---- LEGACY: Topic ↔ Topic edges ---------------------
                    src_topic = str(row.get("source_topic", "")).strip()
                    tgt_topic = str(row.get("target_topic", "")).strip()

                    if not src_topic or not tgt_topic:
                        skip_count += 1
                        continue

                    src_uri = topic_uri_map.get((src_course, src_topic))
                    tgt_uri = topic_uri_map.get((tgt_course, tgt_topic))

                    if src_uri is None or tgt_uri is None:
                        skip_count += 1
                        continue

                    pair = tuple(sorted([str(src_uri), str(tgt_uri)]))
                    if pair in topic_added:
                        continue
                    topic_added.add(pair)

                    g.add((src_uri, MANARA.isRelatedTo, tgt_uri))
                    g.add((tgt_uri, MANARA.isRelatedTo, src_uri))
                    topic_edge_count += 1

    except Exception as e:
        print(f"[KG] Error reading related_subtopics.csv: {e}")
        return

    if subtopic_edge_count:
        print(f"[KG] Added {subtopic_edge_count} isSemanticallySimilarTo subtopic edges "
              f"(distance <= {SIMILARITY_THRESHOLD}, {skip_count} skipped).")
    if topic_edge_count:
        print(f"[KG] Added {topic_edge_count} isRelatedTo topic edges "
              f"(distance <= {SIMILARITY_THRESHOLD}, {skip_count} skipped).")


def _classify_course_relationship(terms: list[str]) -> str:
    text = " ".join(terms).lower()
    math_markers = {
        "matrix", "vector", "linear", "calculus", "probability", "statistics",
        "regression", "optimization", "gradient", "formula", "equation",
        "distance", "similarity", "entropy", "likelihood",
    }
    method_markers = {
        "algorithm", "ranking", "retrieval", "classification", "clustering",
        "search", "index", "embedding", "vector", "pipeline", "query",
        "graph", "tree", "model", "mining", "engineering",
    }
    if any(marker in text for marker in math_markers):
        return "mathematical"
    if any(marker in text for marker in method_markers):
        return "shared_methods"
    return "semantic"


def _edge_explanation(src_course: str, tgt_course: str, terms: list[str], link_count: int) -> str:
    clean_terms = []
    seen = set()
    for term in terms:
        term = str(term).strip()
        key = term.lower()
        if term and key not in seen:
            seen.add(key)
            clean_terms.append(term)
        if len(clean_terms) >= 5:
            break

    concept_text = ", ".join(clean_terms) if clean_terms else "closely related concepts"
    return (
        f"Connected because {src_course} and {tgt_course} share {concept_text}. "
        f"This course-level edge aggregates {link_count} strong subtopic similarity link(s)."
    )


def _collect_course_semantic_edges(limit: int = COURSE_SEMANTIC_EDGE_LIMIT) -> list[dict]:
    """
    Aggregate subtopic-level related_subtopics.csv rows into visible course-level
    edges for the frontend graph. This keeps Manara's brain readable while
    preserving the subtopic evidence behind every connection.
    """
    if not RELATED_CSV.exists():
        print("[KG] related_subtopics.csv missing — no course semantic aggregation.")
        return []

    aggregate: dict[tuple[str, str], dict] = {}

    try:
        with open(RELATED_CSV, "r", encoding="utf-8-sig", newline="") as f:
            reader = csv.DictReader(f)
            for row in reader:
                src_course = str(row.get("source_course", "")).strip()
                tgt_course = str(row.get("target_course", "")).strip()
                if not src_course or not tgt_course or src_course == tgt_course:
                    continue

                try:
                    distance = float(str(row.get("distance", "1")).strip())
                except ValueError:
                    continue
                if distance > SIMILARITY_THRESHOLD:
                    continue

                pair = tuple(sorted([src_course, tgt_course]))
                item = aggregate.setdefault(
                    pair,
                    {
                        "source": pair[0],
                        "target": pair[1],
                        "count": 0,
                        "distance_total": 0.0,
                        "terms": Counter(),
                    },
                )
                item["count"] += 1
                item["distance_total"] += distance

                for key in ("source_topic", "target_topic", "source_subtopic", "target_subtopic"):
                    value = str(row.get(key, "")).strip()
                    if value:
                        item["terms"][value] += 1

    except Exception as exc:
        print(f"[KG] Failed to aggregate course semantic edges: {exc}")
        return []

    edges = []
    for item in aggregate.values():
        if item["count"] < COURSE_SEMANTIC_MIN_LINKS:
            continue
        avg_distance = item["distance_total"] / max(item["count"], 1)
        top_terms = [term for term, _ in item["terms"].most_common(8)]
        relationship = _classify_course_relationship(top_terms)
        strength = min(1.0, (item["count"] / 24.0) * (1.0 - avg_distance))
        edges.append(
            {
                "source_course": item["source"],
                "target_course": item["target"],
                "label": "isSemanticallyRelatedTo",
                "relationship": relationship,
                "strength": round(max(0.12, strength), 3),
                "link_count": int(item["count"]),
                "avg_distance": round(avg_distance, 4),
                "shared_concepts": top_terms[:5],
                "explanation": _edge_explanation(item["source"], item["target"], top_terms, item["count"]),
            }
        )

    edges.sort(key=lambda e: (e["strength"], e["link_count"]), reverse=True)
    print(
        "[KG DEBUG] Course semantic aggregation: "
        f"pairs={len(aggregate)} emitted={min(len(edges), limit)} "
        f"threshold={SIMILARITY_THRESHOLD}"
    )
    return edges[:limit]


